"""Build the web media from source/ into media/ and write lqip.js.

Run from the project folder:  python tools/build_media.py
Needs Pillow and imageio-ffmpeg (pip install pillow imageio-ffmpeg), which ships its own ffmpeg.

source/covers/<slug>.jpg  ->  media/<slug>.webp      (1600 px wide, lightbox and chapters)
                              media/<slug>-sm.webp   (800 px wide, hero deck and index strip)
source/gifs/<slug>.gif    ->  media/<slug>.mp4       (H.264 loop, a fraction of the GIF's size)
all covers                ->  media/og.jpg           (1200 x 630 link preview)
                              lqip.js                (blurred previews painted while images load)
"""
import base64
import io
import json
import subprocess
from pathlib import Path
from urllib.parse import quote

import imageio_ffmpeg
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "source", ROOT / "media"
OUT.mkdir(exist_ok=True)
FFMPEG = imageio_ffmpeg.get_ffmpeg_exe()


def webp(im, width, path, quality):
    h = round(im.height * width / im.width)
    im.resize((width, h), Image.LANCZOS).save(path, "WEBP", quality=quality, method=6)


def lqip(im, w=24):
    h = max(1, round(im.height * w / im.width))
    buf = io.BytesIO()
    im.resize((w, h), Image.LANCZOS).save(buf, "WEBP", quality=60)
    b64 = base64.b64encode(buf.getvalue()).decode()
    svg = (
        f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 {w} {h}' preserveAspectRatio='none'>"
        "<filter id='b' color-interpolation-filters='sRGB'><feGaussianBlur stdDeviation='1.1'/>"
        "<feComponentTransfer><feFuncA type='discrete' tableValues='1 1'/></feComponentTransfer></filter>"
        f"<image width='100%' height='100%' preserveAspectRatio='none' filter='url(#b)' href='data:image/webp;base64,{b64}'/></svg>"
    )
    return "data:image/svg+xml," + quote(svg, safe="/:=+;,.-_~")


def mp4(gif, path):
    # The GIFs run at 10 fps for 4.8 s; keep that timing. yuv420p + faststart so every browser,
    # including iPhone Safari, can start playing before the whole file has arrived.
    subprocess.run([
        FFMPEG, "-y", "-loglevel", "error", "-i", str(gif),
        "-vf", "scale=trunc(iw/2)*2:trunc(ih/2)*2,format=yuv420p",
        "-c:v", "libx264", "-preset", "slow", "-crf", "24", "-movflags", "+faststart", "-an", str(path),
    ], check=True)


def main():
    projects = json.loads((SRC / "projects.json").read_text(encoding="utf-8"))
    previews, covers = {}, []
    for p in projects:
        slug = p["slug"]
        im = Image.open(SRC / "covers" / f"{slug}.jpg").convert("RGB")
        webp(im, 1600, OUT / f"{slug}.webp", 80)
        webp(im, 800, OUT / f"{slug}-sm.webp", 78)
        mp4(SRC / "gifs" / f"{slug}.gif", OUT / f"{slug}.mp4")
        previews[slug] = lqip(im)
        covers.append(im)
        print(slug, "ok")

    # Link preview: the fifteen covers as a 5 x 3 contact sheet.
    og = Image.new("RGB", (1200, 675), "#f4f0e6")
    for i, im in enumerate(covers):
        og.paste(im.resize((240, 135), Image.LANCZOS), ((i % 5) * 240, (i // 5) * 225 + 22))
    og.crop((0, 22, 1200, 652)).save(OUT / "og.jpg", quality=84)

    js = (
        "/* Generated by tools/build_media.py: blurred previews shown while images load. Do not edit by hand. */\n"
        "window.LQIP = " + json.dumps(previews, separators=(",", ":")).replace('","', '",\n"') + ";\n"
    )
    (ROOT / "lqip.js").write_text(js, encoding="utf-8", newline="\n")
    print(f"lqip.js: {len(previews)} previews")


if __name__ == "__main__":
    main()
